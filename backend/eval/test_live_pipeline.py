import asyncio
import os
import sys
from dotenv import load_dotenv

# Load backend/.env
backend_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
env_path = os.path.join(backend_dir, ".env")
load_dotenv(env_path)

sys.path.insert(0, backend_dir)

from app.config import get_settings
from app.services.translation.gemini_translate import GeminiTranslationProvider
from app.services.tts.gnani import GnaniTimbreProvider
from app.services.tts.gemini import GeminiTtsProvider
from app.services.tts.fallback import FallbackTtsProvider
from app.services.stt.gnani import GnaniPrismaProvider
from app.meaning.verifier import verify_translations

async def run_live_diagnostics():
    settings = get_settings()
    print("=== BHARATVAANI LIVE PIPELINE DIAGNOSTIC ===")
    print(f"STT Provider: {settings.stt_provider}")
    print(f"TTS Provider: {settings.tts_provider}")
    print(f"Translation Provider: {settings.translation_provider}")
    print(f"Prisma Endpoint: {settings.prisma_endpoint}")
    print(f"Timbre Endpoint: {settings.timbre_endpoint}")
    print(f"Has Gnani Key: {bool(settings.gnani_api_key_id)}")
    print(f"Has Gemini Key: {bool(settings.gemini_api_key)}")
    print("---------------------------------------------")

    test_hindi_text = "सवा लाख रुपये भेज दीजिए"
    print(f"\n1. Testing Translation (Hindi -> Telugu): '{test_hindi_text}'")
    translator = GeminiTranslationProvider(
        api_key=settings.gemini_api_key,
        model=settings.gemini_model,
        fallback_model=settings.gemini_fallback_model
    )
    tr_res = await translator.translate(test_hindi_text, "hi", "te")
    print(f"  Translated text: {tr_res.translated_text}")
    print(f"  Speech text: {tr_res.speech_text}")
    if tr_res.error:
        print(f"  Translation error: {tr_res.error}")

    print(f"\n2. Testing Meaning Verification on '{test_hindi_text}' vs '{tr_res.translated_text}'")
    ver_res = verify_translations(test_hindi_text, tr_res.translated_text)
    print(f"  Verification status: {ver_res['status']}")
    print(f"  Prompt to speaker: {ver_res['prompt_to_speaker']}")
    print(f"  Original amounts: {ver_res['entities_original'].get('amounts')}")
    print(f"  Translated amounts: {ver_res['entities_translated'].get('amounts')}")

    print(f"\n3. Testing Gnani Timbre TTS directly with Telugu: '{tr_res.translated_text}'")
    gnani_tts = GnaniTimbreProvider(
        api_key_id=settings.gnani_api_key_id,
        endpoint=settings.timbre_endpoint,
        telugu_voice=settings.timbre_telugu_voice
    )
    gnani_res = await gnani_tts.synthesize(tr_res.translated_text, "te")
    print(f"  Gnani Timbre returned bytes: {len(gnani_res.audio_bytes)}")
    print(f"  Gnani Timbre error: {gnani_res.error}")

    tts_audio_to_test = None
    if gnani_res.audio_bytes and len(gnani_res.audio_bytes) > 44:
        print("  -> Gnani Timbre SUCCESS!")
        tts_audio_to_test = gnani_res.audio_bytes
    else:
        print("  -> Gnani Timbre failed or empty, testing Fallback TTS (Gemini)...")
        fallback_tts = FallbackTtsProvider(gnani_tts, GeminiTtsProvider(settings.gemini_api_key, settings.gemini_tts_model))
        fb_res = await fallback_tts.synthesize(tr_res.translated_text, "te")
        print(f"  Fallback TTS returned bytes: {len(fb_res.audio_bytes)}")
        print(f"  Fallback TTS format: {fb_res.audio_format}")
        print(f"  Fallback TTS error: {fb_res.error}")
        tts_audio_to_test = fb_res.audio_bytes

    print(f"\n4. Testing Gnani Prisma STT with generated audio ({len(tts_audio_to_test or b'')} bytes)")
    if tts_audio_to_test and len(tts_audio_to_test) > 44:
        stt = GnaniPrismaProvider(api_key_id=settings.gnani_api_key_id, endpoint=settings.prisma_endpoint)
        stt_res = await stt.transcribe(tts_audio_to_test, "te")
        print(f"  Prisma Transcribed text: '{stt_res.text}'")
        print(f"  Prisma Language: {stt_res.language}")
        print(f"  Prisma is_empty: {stt_res.is_empty}")
        if stt_res.error:
            print(f"  Prisma Error: {stt_res.error}")
    else:
        print("  Skipping STT test: No valid audio generated by TTS.")

    print("\n=== PIPELINE DIAGNOSTIC COMPLETE ===")

if __name__ == "__main__":
    asyncio.run(run_live_diagnostics())
